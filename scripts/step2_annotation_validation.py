# 11. VISUALIZE SAMPLE
# ============================================================================

def visualize_sample(
    coco,
    n=VISUALIZATION_COUNT,
):
    """
    Draw annotations on a sample of images.

    The sample includes both positive and negative images.
    """

    VIS_OUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    anns_by_image = defaultdict(list)

    for ann in coco["annotations"]:

        anns_by_image[
            ann["image_id"]
        ].append(ann)

    selected_images = coco["images"][:n]

    for image_meta in tqdm(
        selected_images,
        desc="Creating annotation previews",
    ):

        image_path = (
            IMAGES_DIR
            / image_meta["file_name"]
        )

        image = cv2.imread(
            str(image_path)
        )

        if image is None:
            continue

        annotations = anns_by_image.get(
            image_meta["id"],
            [],
        )

        for ann in annotations:

            x, y, w, h = (
                ann["bbox"]
            )

            x1 = max(
                0,
                int(round(x))
            )

            y1 = max(
                0,
                int(round(y))
            )

            x2 = min(
                image.shape[1] - 1,
                int(round(x + w))
            )

            y2 = min(
                image.shape[0] - 1,
                int(round(y + h))
            )

            cv2.rectangle(
                image,
                (x1, y1),
                (x2, y2),
                (0, 255, 0),
                2,
            )

            cv2.putText(
                image,
                "snake",
                (x1, max(20, y1 - 5)),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.6,
                (0, 255, 0),
                2,
            )

        output_path = (
            VIS_OUT_DIR
            / image_meta["file_name"]
        )

        cv2.imwrite(
            str(output_path),
            image,
        )

    print(
        f"Annotation previews saved to: "
        f"{VIS_OUT_DIR}"
    )


