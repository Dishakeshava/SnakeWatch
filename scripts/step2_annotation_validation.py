# 10. ANNOTATION STATISTICS
# ============================================================================

def calculate_statistics(coco):
    """Calculate useful annotation statistics."""

    image_lookup = {
        image["id"]: image
        for image in coco["images"]
    }

    anns_by_image = defaultdict(list)

    for ann in coco["annotations"]:
        anns_by_image[
            ann["image_id"]
        ].append(ann)

    positive_image_ids = set(
        anns_by_image.keys()
    )

    negative_images = [
        image
        for image in coco["images"]
        if image["id"]
        not in positive_image_ids
    ]

    boxes = [
        ann["bbox"]
        for ann in coco["annotations"]
    ]

    widths = [
        box[2]
        for box in boxes
    ]

    heights = [
        box[3]
        for box in boxes
    ]

    total_images = len(
        coco["images"]
    )

    total_annotations = len(
        coco["annotations"]
    )

    positive_count = len(
        positive_image_ids
    )

    negative_count = len(
        negative_images
    )

    statistics = {
        "total_images": total_images,
        "positive_images": positive_count,
        "negative_images": negative_count,
        "positive_percentage": (
            positive_count / total_images * 100
            if total_images
            else 0
        ),
        "negative_percentage": (
            negative_count / total_images * 100
            if total_images
            else 0
        ),
        "total_snake_annotations": total_annotations,
        "average_snakes_per_positive_image": (
            total_annotations / positive_count
            if positive_count
            else 0
        ),
        "average_box_width": (
            sum(widths) / len(widths)
            if widths
            else 0
        ),
        "average_box_height": (
            sum(heights) / len(heights)
            if heights
            else 0
        ),
    }

    return statistics


