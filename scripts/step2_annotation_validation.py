def save_report(
    statistics,
    validation,
    conversion_issues,
    metadata_issues,
):
    """Save all QA information as JSON."""

    report = {
        "statistics": statistics,

        "conversion_issues": conversion_issues,

        "metadata_crosscheck_issues":
            metadata_issues,

        "validation": {
            "structural_issues":
                validation["issues"],

            "warnings":
                validation["warnings"],

            "suspicious_small_boxes":
                validation[
                    "suspicious_small_boxes"
                ],

            "suspicious_large_boxes":
                validation[
                    "suspicious_large_boxes"
                ],

            "suspicious_thin_boxes":
                validation[
                    "suspicious_thin_boxes"
                ],

            "possible_duplicate_boxes":
                validation[
                    "possible_duplicate_boxes"
                ],
        },
    }

    REPORT_OUT_PATH.write_text(
        json.dumps(
            report,
            indent=2,
        ),
        encoding="utf-8",
    )

    return report


