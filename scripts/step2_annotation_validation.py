"""
Step 2: Annotation Validation and COCO Conversion
-------------------------------------------------

Purpose:
    1. Convert YOLO annotations to COCO JSON
    2. Validate annotation structure
    3. Check class IDs
    4. Detect invalid / zero-area / out-of-bounds boxes
    5. Flag suspiciously small or large boxes
    6. Detect highly-overlapping duplicate annotations
    7. Verify image files
    8. Generate annotation statistics
    9. Create visual annotation previews

Expected input from Step 1:

dataset/
    images/
        *.jpg
    metadata.csv

YOLO labels should be placed in:

dataset/
    yolo_labels/
        image_name.txt

YOLO format:

    class_id x_center y_center width height

All coordinates are normalized to [0, 1].

For this project:

    class 0 = snake

Hard negatives such as rope/hose/cable/vine should have
EMPTY annotation files (or no annotation file).

Output:

dataset/
    annotations.json
    annotation_report.json
    annotation_check/
        *.jpg

Install:

    pip install opencv-python pillow tqdm
"""

import json
import csv
from pathlib import Path
from collections import defaultdict, Counter

import cv2
from tqdm import tqdm


# ============================================================================
# 1. CONFIGURATION
# ============================================================================

DATASET_DIR = Path("dataset")

IMAGES_DIR = DATASET_DIR / "images"
YOLO_LABELS_DIR = DATASET_DIR / "yolo_labels"

COCO_OUT_PATH = DATASET_DIR / "annotations.json"
REPORT_OUT_PATH = DATASET_DIR / "annotation_report.json"

VIS_OUT_DIR = DATASET_DIR / "annotation_check"

METADATA_PATH = DATASET_DIR / "metadata.csv"


# Only one detector class.
# Background/hard-negative objects are NOT detector classes.
CATEGORIES = [
    {
        "id": 1,
        "name": "snake",
        "supercategory": "animal",
    }
]

VALID_YOLO_CLASS_IDS = {0}


# ---------------------------------------------------------------------------
# Suspicious annotation thresholds
# ---------------------------------------------------------------------------

# Boxes smaller than this fraction of image area are flagged.
MIN_BOX_AREA_RATIO = 0.00005

# Boxes larger than this fraction of image area are flagged.
MAX_BOX_AREA_RATIO = 0.95

# Extremely thin boxes may indicate annotation mistakes.
MIN_BOX_SIDE_PIXELS = 2


# IoU threshold for duplicate-box warning.
DUPLICATE_IOU_THRESHOLD = 0.90


# Number of images to preview.
VISUALIZATION_COUNT = 30


# ============================================================================
# 2. CHECK DIRECTORIES
# ============================================================================

def check_input_directories():
    """Check that Step 1 output and YOLO labels exist."""

    if not DATASET_DIR.exists():
        raise FileNotFoundError(
            f"Dataset directory not found: {DATASET_DIR}"
        )

    if not IMAGES_DIR.exists():
        raise FileNotFoundError(
            f"Images directory not found: {IMAGES_DIR}"
        )

    if not YOLO_LABELS_DIR.exists():
        raise FileNotFoundError(
            f"YOLO labels directory not found: {YOLO_LABELS_DIR}\n"
            f"Create it and place your annotation .txt files there."
        )


# ============================================================================
# 3. LOAD STEP 1 METADATA
# ============================================================================

def load_metadata():
    """
    Load metadata generated by Step 1.

    This is used to verify that the annotation dataset still corresponds
    to the curated dataset.
    """

    if not METADATA_PATH.exists():
        print(
            "⚠ metadata.csv not found."
        )
        print(
            "Continuing without metadata cross-check."
        )
        return {}

    metadata = {}

    with METADATA_PATH.open(
        "r",
        newline="",
        encoding="utf-8",
    ) as f:

        reader = csv.DictReader(f)

        for row in reader:
            metadata[row["filename"]] = row

    print(
        f"Loaded metadata for {len(metadata)} images."
    )

    return metadata


# ============================================================================
# 4. FIND IMAGE FILES
# ============================================================================

def get_image_files():
    """Return all supported images."""

    extensions = {
        ".jpg",
        ".jpeg",
        ".png",
        ".bmp",
        ".webp",
    }

    files = sorted(
        p for p in IMAGES_DIR.iterdir()
        if p.is_file() and p.suffix.lower() in extensions
    )

    return files


# ============================================================================
# 5. YOLO BOX CONVERSION
# ============================================================================

def yolo_to_absolute(
    xc,
    yc,
    bw,
    bh,
    image_width,
    image_height,
):
    """
    Convert normalized YOLO coordinates into absolute COCO coordinates.

    YOLO:
        x_center
        y_center
        width
        height

    COCO:
        x_min
        y_min
        width
        height
    """

    abs_w = bw * image_width
    abs_h = bh * image_height

    x_min = (
        xc * image_width
        - abs_w / 2
    )

    y_min = (
        yc * image_height
        - abs_h / 2
    )

    return [
        x_min,
        y_min,
        abs_w,
        abs_h,
    ]


# ============================================================================
# 6. IOU
# ============================================================================

def calculate_iou(box_a, box_b):
    """
    Calculate IoU for COCO-format boxes:

        [x, y, width, height]
    """

    ax, ay, aw, ah = box_a
    bx, by, bw, bh = box_b

    ax2 = ax + aw
    ay2 = ay + ah

    bx2 = bx + bw
    by2 = by + bh

    intersection_x1 = max(ax, bx)
    intersection_y1 = max(ay, by)

    intersection_x2 = min(ax2, bx2)
    intersection_y2 = min(ay2, by2)

    intersection_w = max(
        0,
        intersection_x2 - intersection_x1,
    )

    intersection_h = max(
        0,
        intersection_y2 - intersection_y1,
    )

    intersection_area = (
        intersection_w * intersection_h
    )

    area_a = aw * ah
    area_b = bw * bh

    union_area = (
        area_a
        + area_b
        - intersection_area
    )

    if union_area <= 0:
        return 0.0

    return intersection_area / union_area


# ============================================================================
# 7. CONVERT YOLO → COCO
# ============================================================================

def convert_yolo_to_coco(
    image_files,
    metadata,
):
    """
    Convert all YOLO annotations to COCO.

    Images without labels are intentionally included as negative images.
    """

    coco_images = []
    coco_annotations = []

    annotation_id = 1

    conversion_issues = []

    positive_images = 0
    negative_images = 0

    image_id = 1

    for image_path in tqdm(
        image_files,
        desc="Converting YOLO → COCO",
    ):

        image = cv2.imread(
            str(image_path)
        )

        if image is None:

            conversion_issues.append(
                f"Could not read image: "
                f"{image_path.name}"
            )

            continue

        height, width = image.shape[:2]

        coco_images.append(
            {
                "id": image_id,
                "file_name": image_path.name,
                "width": width,
                "height": height,
            }
        )

        label_path = (
            YOLO_LABELS_DIR
            / f"{image_path.stem}.txt"
        )

        if (
            not label_path.exists()
            or not label_path.read_text(
                encoding="utf-8"
            ).strip()
        ):

            negative_images += 1
            image_id += 1
            continue

        positive_images += 1

        lines = label_path.read_text(
            encoding="utf-8"
        ).strip().splitlines()

        for line_number, line in enumerate(
            lines,
            start=1,
        ):

            if not line.strip():
                continue

            parts = line.split()

            if len(parts) != 5:

                conversion_issues.append(
                    f"{image_path.name}: "
                    f"line {line_number} "
                    f"does not contain exactly 5 values"
                )

                continue

            try:

                cls = int(parts[0])

                xc = float(parts[1])
                yc = float(parts[2])
                bw = float(parts[3])
                bh = float(parts[4])

            except ValueError:

                conversion_issues.append(
                    f"{image_path.name}: "
                    f"line {line_number} "
                    f"contains invalid numeric values"
                )

                continue

            if cls not in VALID_YOLO_CLASS_IDS:

                conversion_issues.append(
                    f"{image_path.name}: "
                    f"invalid class ID {cls}"
                )

                continue

            # Normalized coordinate sanity check.
            if not (
                0 <= xc <= 1
                and 0 <= yc <= 1
                and 0 < bw <= 1
                and 0 < bh <= 1
            ):

                conversion_issues.append(
                    f"{image_path.name}: "
                    f"invalid normalized box values "
                    f"at line {line_number}"
                )

                continue

            bbox = yolo_to_absolute(xc, yc, bw, bh, width, height)
            x, y, box_w, box_h = bbox

            # Clip to valid image bounds instead of just logging the problem.
            x1 = max(0.0, x)
            y1 = max(0.0, y)
            x2 = min(width, x + box_w)
            y2 = min(height, y + box_h)

            box_w = x2 - x1
            box_h = y2 - y1

            if box_w <= 0 or box_h <= 0:
                conversion_issues.append(
                    f"{image_path.name}: line {line_number} "
                    f"box fell entirely outside bounds after clipping, dropped"
                )
                continue

            coco_annotations.append({
                "id": annotation_id,
                "image_id": image_id,
                "category_id": 1,
                "bbox": [x1, y1, box_w, box_h],
                "area": box_w * box_h,
                "iscrowd": 0,
            })
            annotation_id += 1

        image_id += 1

    coco = {
        "images": coco_images,
        "annotations": coco_annotations,
        "categories": CATEGORIES,
    }

    COCO_OUT_PATH.write_text(
        json.dumps(
            coco,
            indent=2,
        ),
        encoding="utf-8",
    )

    print(
        f"\nCOCO file written to: "
        f"{COCO_OUT_PATH}"
    )

    print(
        f"Images: {len(coco_images)}"
    )

    print(
        f"Positive images: {positive_images}"
    )

    print(
        f"Negative images: {negative_images}"
    )

    print(
        f"Annotations: "
        f"{len(coco_annotations)}"
    )

    return coco, conversion_issues


# ============================================================================
# 8. VALIDATE COCO ANNOTATIONS
# ============================================================================

def validate_coco(coco):
    """
    Perform structural and semantic annotation validation.
    """

    issues = []
    warnings = []

    image_lookup = {
        image["id"]: image
        for image in coco["images"]
    }

    category_ids = {
        category["id"]
        for category in coco["categories"]
    }

    annotation_count_by_image = Counter()

    suspicious_small = 0
    suspicious_large = 0
    suspicious_thin = 0
    duplicate_boxes = 0

    # ------------------------------------------------------------------------
    # Annotation-level checks
    # ------------------------------------------------------------------------

    for ann in coco["annotations"]:

        ann_id = ann["id"]

        image_id = ann["image_id"]

        image = image_lookup.get(
            image_id
        )

        if image is None:

            issues.append(
                f"Annotation {ann_id} "
                f"references missing image "
                f"ID {image_id}"
            )

            continue

        category_id = ann.get(
            "category_id"
        )

        if category_id not in category_ids:

            issues.append(
                f"Annotation {ann_id}: "
                f"invalid category ID "
                f"{category_id}"
            )

        x, y, w, h = ann["bbox"]

        image_width = image["width"]
        image_height = image["height"]

        # ------------------------------------------------------------
        # Zero/negative box
        # ------------------------------------------------------------

        if w <= 0 or h <= 0:

            issues.append(
                f"Annotation {ann_id}: "
                f"zero/negative-area box in "
                f"{image['file_name']}"
            )

        # ------------------------------------------------------------
        # Out-of-bounds
        # ------------------------------------------------------------

        if (
            x < 0
            or y < 0
            or x + w > image_width
            or y + h > image_height
        ):

            issues.append(
                f"Annotation {ann_id}: "
                f"box outside image bounds in "
                f"{image['file_name']}"
            )

        # ------------------------------------------------------------
        # Area ratio
        # ------------------------------------------------------------

        image_area = (
            image_width
            * image_height
        )

        box_area = w * h

        area_ratio = (
            box_area / image_area
            if image_area > 0
            else 0
        )

        if area_ratio < MIN_BOX_AREA_RATIO:

            warnings.append(
                f"Annotation {ann_id}: "
                f"very small box "
                f"({area_ratio:.6f} of image) "
                f"in {image['file_name']}"
            )

            suspicious_small += 1

        if area_ratio > MAX_BOX_AREA_RATIO:

            warnings.append(
                f"Annotation {ann_id}: "
                f"very large box "
                f"({area_ratio:.3f} of image) "
                f"in {image['file_name']}"
            )

            suspicious_large += 1

        # ------------------------------------------------------------
        # Thin-box check
        # ------------------------------------------------------------

        if (
            w < MIN_BOX_SIDE_PIXELS
            or h < MIN_BOX_SIDE_PIXELS
        ):

            warnings.append(
                f"Annotation {ann_id}: "
                f"extremely thin/small box "
                f"in {image['file_name']}"
            )

            suspicious_thin += 1

        annotation_count_by_image[
            image_id
        ] += 1

    # ------------------------------------------------------------------------
    # Duplicate annotation check
    # ------------------------------------------------------------------------

    anns_by_image = defaultdict(list)

    for ann in coco["annotations"]:
        anns_by_image[
            ann["image_id"]
        ].append(ann)

    for image_id, anns in anns_by_image.items():

        if len(anns) < 2:
            continue

        image_name = image_lookup[
            image_id
        ]["file_name"]

        for i in range(len(anns)):

            for j in range(i + 1, len(anns)):

                iou = calculate_iou(
                    anns[i]["bbox"],
                    anns[j]["bbox"],
                )

                if iou >= DUPLICATE_IOU_THRESHOLD:

                    warnings.append(
                        f"Possible duplicate "
                        f"annotations in "
                        f"{image_name}: "
                        f"annotation "
                        f"{anns[i]['id']} and "
                        f"{anns[j]['id']} "
                        f"(IoU={iou:.3f})"
                    )

                    duplicate_boxes += 1

    # ------------------------------------------------------------------------
    # Verify image files
    # ------------------------------------------------------------------------

    for image in coco["images"]:

        image_path = (
            IMAGES_DIR
            / image["file_name"]
        )

        if not image_path.exists():

            issues.append(
                f"Image missing on disk: "
                f"{image['file_name']}"
            )

    return {
        "issues": issues,
        "warnings": warnings,
        "suspicious_small_boxes": suspicious_small,
        "suspicious_large_boxes": suspicious_large,
        "suspicious_thin_boxes": suspicious_thin,
        "possible_duplicate_boxes": duplicate_boxes,
        "annotation_count_by_image": dict(
            annotation_count_by_image
        ),
    }


# ============================================================================
# 9. CROSS-CHECK STEP 1 METADATA
# ============================================================================

def cross_check_metadata(
    coco,
    metadata,
):
    """
    Check whether every curated image still exists in the annotation dataset.

    This does not require every image to have an annotation because negative
    samples intentionally have no snake boxes.
    """

    if not metadata:
        return []

    issues = []

    coco_filenames = {
        image["file_name"]
        for image in coco["images"]
    }

    for filename in metadata:

        if filename not in coco_filenames:

            issues.append(
                f"Metadata image missing from "
                f"COCO dataset: {filename}"
            )

    for filename in coco_filenames:

        if filename not in metadata:

            issues.append(
                f"COCO image missing from "
                f"Step 1 metadata: {filename}"
            )

    return issues


